QUESTIONS = []


def paper(paper_id, text):
    for line in text.strip().splitlines():
        if not line.strip():
            continue
        ref, page, marks, key, prompt = line.split("|")
        assert key in ANSWERS, f"Unknown answer key: {key}"
        QUESTIONS.append(
            dict(
                paper=paper_id,
                ref=ref,
                page=int(page),
                marks=marks,
                key=key,
                prompt=prompt,
            )
        )


